let language = localStorage.getItem('afterday-language') === 'en' ? 'en' : 'th';
const originalText = new WeakMap();
const originalAttributes = new WeakMap();
window.translateText = text => language === 'en' ? (english.get(text) || text) : text;
window.getSiteLanguage = () => language;

function translatePage() {
  document.documentElement.lang = language;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const current = node.textContent;
    const trimmed = current.trim();
    if (!trimmed) continue;
    if (language === 'en') {
      if (english.has(trimmed)) {
        originalText.set(node, current);
        node.textContent = current.replace(trimmed, english.get(trimmed));
      }
    } else if (originalText.has(node)) {
      node.textContent = originalText.get(node);
    }
  }
  document.querySelectorAll('*').forEach(element => {
    for (const name of ['alt', 'aria-label', 'title']) {
      if (!element.hasAttribute(name)) continue;
      const value = element.getAttribute(name);
      if (language === 'en' && english.has(value)) {
        let originals = originalAttributes.get(element);
        if (!originals) { originals = {}; originalAttributes.set(element, originals); }
        originals[name] = value;
        element.setAttribute(name, english.get(value));
      } else if (language === 'th') {
        const original = originalAttributes.get(element)?.[name];
        if (original) element.setAttribute(name, original);
      }
    }
  });
  document.title = 'AfterDay Horizon';
  document.querySelector('meta[name=description]').content = language === 'en'
    ? 'AfterDay Horizon is a cooperative survival game for two players across VR and the web.'
    : 'AfterDay Horizon เกมเอาชีวิตรอดแบบร่วมมือสำหรับผู้เล่นสองคน ผ่าน VR และเว็บไซต์';
  const toggle = document.getElementById('language-toggle');
  toggle.textContent = language === 'en' ? 'TH' : 'EN';
  toggle.setAttribute('aria-label', language === 'en' ? 'Switch to Thai' : 'Switch to English');
  toggle.setAttribute('aria-pressed', String(language === 'en'));
}

document.getElementById('language-toggle').addEventListener('click', () => {
  language = language === 'th' ? 'en' : 'th';
  localStorage.setItem('afterday-language', language);
  translatePage();
  window.dispatchEvent(new Event('afterday:language-change'));
});
translatePage();
